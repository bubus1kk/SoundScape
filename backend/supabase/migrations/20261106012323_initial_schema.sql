-- 35. INTERNAL API QUOTA COUNTERS
-- Technical table outside the 29-table ER model.
-- =============================================

CREATE TABLE internal.api_quota_counters (
    scope_type TEXT NOT NULL,

    subject_key TEXT NOT NULL,

    operation_code TEXT NOT NULL,

    window_started_at TIMESTAMPTZ NOT NULL,

    request_count BIGINT NOT NULL DEFAULT 0,

    active_lease_id UUID,

    active_lease_expires_at TIMESTAMPTZ,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (
        scope_type,
        subject_key,
        operation_code,
        window_started_at
    ),

    CONSTRAINT api_quota_scope_check
        CHECK (scope_type IN ('GLOBAL', 'USER')),

    CONSTRAINT api_quota_subject_check
        CHECK (char_length(btrim(subject_key)) > 0),

    CONSTRAINT api_quota_operation_check
        CHECK (char_length(btrim(operation_code)) > 0),

    CONSTRAINT api_quota_count_check
        CHECK (request_count >= 0),

    CONSTRAINT api_quota_lease_check
        CHECK (
            (active_lease_id IS NULL)
            = (active_lease_expires_at IS NULL)
        )
);

CREATE INDEX api_quota_counters_updated_idx
    ON internal.api_quota_counters (updated_at);

-- This schema is not exposed through PostgREST.
-- Client roles must never access quota counters.

REVOKE ALL ON TABLE internal.api_quota_counters
    FROM PUBLIC, anon, authenticated;

