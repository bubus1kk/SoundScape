        REFERENCES public.profiles(id)
        ON DELETE CASCADE,

    token_hash TEXT NOT NULL UNIQUE,

    playlist_id UUID
        REFERENCES public.playlists(id)
        ON DELETE CASCADE,

    pin_id UUID
        REFERENCES public.music_pins(id)
        ON DELETE CASCADE,

    event_id UUID
        REFERENCES public.travel_events(id)
        ON DELETE CASCADE,

    journey_id UUID
        REFERENCES public.music_journeys(id)
        ON DELETE CASCADE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    expires_at TIMESTAMPTZ,

    revoked_at TIMESTAMPTZ,

    CONSTRAINT share_tokens_hash_check
        CHECK (char_length(btrim(token_hash)) > 0),

    CONSTRAINT share_tokens_target_check
        CHECK (
            num_nonnulls(
                playlist_id,
                pin_id,
                event_id,
                journey_id
            ) = 1
        ),

    CONSTRAINT share_tokens_expiration_check
        CHECK (
            expires_at IS NULL
            OR expires_at > created_at
        ),

    CONSTRAINT share_tokens_revocation_check
        CHECK (
            revoked_at IS NULL
            OR revoked_at >= created_at
        )
);

CREATE INDEX share_tokens_owner_created_idx
    ON public.share_tokens (owner_id, created_at DESC);

CREATE INDEX share_tokens_playlist_idx
    ON public.share_tokens (playlist_id)
    WHERE playlist_id IS NOT NULL;

