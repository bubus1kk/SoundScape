$ErrorActionPreference = 'Stop'

function Test-RestoreSequences {
  param([scriptblock]$Psql, [string]$ScriptsPath)

  function Assert-Sql {
    param([string]$Sql, [string]$Expected = '')
    $result = & $Psql $Sql 2>&1
    if ($LASTEXITCODE -ne 0 -or ($Expected -and @($result)[-1] -ne $Expected)) {
      throw ('Unexpected SQL result: ' + ($result -join [Environment]::NewLine))
    }
  }

  function Assert-SqlFailure {
    param([string]$Sql, [string]$Expected)
    $result = & $Psql $Sql 2>&1
    if (!$LASTEXITCODE -or ($result -join ' ') -notlike "*$Expected*") {
      throw ('Expected SQL failure: ' + $Expected + '. Actual: ' + ($result -join ' '))
    }
  }

  $verify = Get-Content -Raw -LiteralPath (Join-Path $ScriptsPath 'verify-restore-sequences.sql')
  $repair = Get-Content -Raw -LiteralPath (Join-Path $ScriptsPath '../supabase/migrations/20261128072129_be05_realign_catalog_identity.sql')

  Assert-Sql @'
CREATE TABLE public.genres(id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.moods(id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.tags(id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.tracks (
  id uuid PRIMARY KEY,
  genre_id smallint NOT NULL REFERENCES public.genres(id),
  tag_id smallint NOT NULL REFERENCES public.tags(id)
);
INSERT INTO public.genres(id, name) VALUES (1, 'Synthetic'), (42, 'Highest');
INSERT INTO public.tags(id, name) VALUES (1, 'Synthetic'), (66, 'Highest');
INSERT INTO public.moods(id, name) VALUES (2, 'Existing');
ALTER SEQUENCE public.moods_id_seq RESTART WITH 20;
INSERT INTO public.tracks VALUES ('12345678-1234-4234-8234-123456789abc', 42, 66);
'@

  $drift = 'cannot safely allocate a new ID: public.genres.id, public.tags.id'
  $exhausted = 'No ID available above the current catalog state for public.tags.id'
  $readState = @'
SELECT concat_ws('|', g.last_value, g.is_called::int, m.last_value, m.is_called::int, t.last_value, t.is_called::int)
FROM public.genres_id_seq g, public.moods_id_seq m, public.tags_id_seq t;
'@
  Assert-SqlFailure $verify $drift
  Assert-Sql $readState '1|0|20|0|1|0'

  # An explicit rollback must undo RESTART and the write-blocking locks must still be held.
  $assertLocks = @'
SELECT count(*) FROM pg_locks
WHERE pid = pg_backend_pid() AND granted AND mode = 'ShareRowExclusiveLock'
  AND relation IN ('public.genres'::regclass, 'public.moods'::regclass, 'public.tags'::regclass);
ROLLBACK;
'@
  Assert-Sql (@('BEGIN;', $repair, $assertLocks) -join [Environment]::NewLine) '3'
  Assert-Sql $readState '1|0|20|0|1|0'

  Assert-Sql $repair
  Assert-Sql $verify
  Assert-Sql $readState '43|0|20|0|67|0'
  Assert-Sql $repair
  Assert-Sql $readState '43|0|20|0|67|0'

  Assert-Sql @'
SELECT (SELECT jsonb_agg(to_jsonb(g) ORDER BY id) FROM public.genres g)
       = '[{"id":1,"name":"Synthetic"},{"id":42,"name":"Highest"}]'::jsonb
   AND (SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM public.moods m)
       = '[{"id":2,"name":"Existing"}]'::jsonb
   AND (SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM public.tags t)
       = '[{"id":1,"name":"Synthetic"},{"id":66,"name":"Highest"}]'::jsonb
   AND (SELECT jsonb_agg(to_jsonb(tr) ORDER BY id) FROM public.tracks tr)
       = '[{"id":"12345678-1234-4234-8234-123456789abc","tag_id":66,"genre_id":42}]'::jsonb;
'@ 't'

  Assert-Sql "INSERT INTO public.genres(name) VALUES ('New') RETURNING id;" '43'
  Assert-Sql "INSERT INTO public.tags(name) VALUES ('New') RETURNING id;" '67'
  Assert-Sql $repair
  Assert-Sql $readState '43|1|20|0|67|1'

  # The last valid smallint can be assigned. A subsequent repair must fail atomically.
  Assert-Sql @'
INSERT INTO public.tags(id, name) VALUES (32766, 'Penultimate');
ALTER SEQUENCE public.genres_id_seq RESTART WITH 1;
'@
  Assert-Sql $repair
  Assert-Sql $readState '44|0|20|0|32767|0'
  Assert-Sql "INSERT INTO public.tags(name) VALUES ('Last') RETURNING id;" '32767'
  Assert-Sql 'ALTER SEQUENCE public.genres_id_seq RESTART WITH 1;'
  Assert-SqlFailure $repair $exhausted
  Assert-Sql $readState '1|0|20|0|32767|1'
  Assert-SqlFailure $verify $drift
  Assert-Sql $readState '1|0|20|0|32767|1'

  # A full table also prevents repair while the counter is still behind.
  Assert-Sql 'ALTER SEQUENCE public.tags_id_seq RESTART WITH 1;'
  Assert-SqlFailure $repair $exhausted
  Assert-Sql $readState '1|0|20|0|1|0'
  'PASS: catalog drift, locks, rollback, repeatability, unchanged rows/UUID/FKs and smallint bounds'
}

$container = 'ss-be05-sequence-regression-' + [guid]::NewGuid().ToString('N').Substring(0, 8)
$image = 'public.ecr.aws/supabase/postgres:17.11.0.011'
docker image inspect $image | Out-Null
if ($LASTEXITCODE) { throw 'Expected cached image unavailable' }

docker run --detach --rm --network none --name $container -e POSTGRES_PASSWORD=synthetic-local-only $image | Out-Null
if ($LASTEXITCODE) { throw 'Fixture PostgreSQL startup failed' }
try {
  for ($attempt = 0; $attempt -lt 40; $attempt++) {
    # The image initializes on a socket before starting its final TCP listener.
    docker exec $container pg_isready -h 127.0.0.1 -U postgres 2>$null | Out-Null
    if (!$LASTEXITCODE) { break }
    Start-Sleep -Milliseconds 500
  }
  if ($LASTEXITCODE) { throw 'Fixture PostgreSQL unavailable' }

  Test-RestoreSequences -ScriptsPath $PSScriptRoot -Psql {
    param([string]$Sql)
    $Sql | docker exec -i $container psql -XqAt -U postgres -d postgres -v ON_ERROR_STOP=1
  }
} finally {
  docker stop $container | Out-Null
  if ($LASTEXITCODE) { throw 'Could not stop the fixture container' }
}
